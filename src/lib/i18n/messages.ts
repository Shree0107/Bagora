export type MessageKey = keyof typeof en;


export type Translate = (key: MessageKey | (string & {}), vars?: Record<string, string | number>) => string;

/** Build the translate function. Unknown keys are returned as-is. */
export function translator(): Translate {
  return (key, vars) => {
    let text: string = en[key as MessageKey] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}
